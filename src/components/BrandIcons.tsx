/**
 * 依据 issuer / account 查找内置品牌图标。
 * 返回 null 表示未收录，调用方应回退到首字母头像（或联网抓取 favicon）。
 */
export function findBrandIcon(...candidates: Array<string | undefined>): BrandIcon | null {
  for (const raw of candidates) {
    if (!raw) continue;
    const value = raw.toLowerCase();
    for (const brand of BRAND_ICONS) {
      if (brand.keys.some((k) => value.includes(k))) return brand;
    }
  }
  return null;
}
